#!/usr/bin/env python3
"""Write include/nes_prg_crc.h with the CRC-32 of the PRG image rebuilt from the ASM (the ROM the recompiled code assumes)."""
import sys, zlib, subprocess, tempfile, os
asm = sys.argv[1]
tmp = tempfile.NamedTemporaryFile(delete=False); tmp.close()
subprocess.check_call([sys.executable, os.path.join(os.path.dirname(__file__), 'asm_to_prg.py'), asm, tmp.name], stdout=subprocess.DEVNULL)
crc = zlib.crc32(open(tmp.name, 'rb').read()) & 0xFFFFFFFF
os.unlink(tmp.name)
open('include/nes_prg_crc.h', 'w').write('/* GENERATED by tools/gen_prg_crc.py */\n#define NES_EXPECTED_PRG_CRC32 0x%08XUL\n' % crc)
print('crc %08X' % crc)
