#!/usr/bin/env python3
"""Write tests/oracle/region_list.h: start addresses of every label region (sub_/loc_/ofs_/vec_) of bank_FF.asm."""
import sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
asm = sys.argv[1]
sys.argv = [sys.argv[0], asm, 'C99A']
import callgraph as cg
addrs = sorted({r['addr'] for r in cg.regions})
with open('tests/oracle/region_list.h', 'w') as f:
    f.write('/* GENERATED by tools/gen_region_list.py */\nstatic const uint16_t kRegions[] = {\n')
    for i in range(0, len(addrs), 8): f.write('    ' + ', '.join('0x%04X' % a for a in addrs[i:i+8]) + ',\n')
    f.write('};\n')
print(len(addrs))
