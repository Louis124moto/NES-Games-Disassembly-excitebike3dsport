#!/usr/bin/env python3
"""Generate include/nes_race_decl.h (prototypes) and tests/oracle/fallbacks.c (weak oracle-backed stubs) for every
sub_/loc_/ofs_ region of bank_FF.asm. Name scheme: nesR_<ADDR> (4 hex digits).  Usage: gen_routine_decls.py bank_FF.asm"""
import re, sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
sys.argv = [sys.argv[0], sys.argv[1], 'C99A']
import callgraph as cg
addrs = sorted({r['addr'] for r in cg.regions})
with open('include/nes_race_decl.h', 'w') as f:
    f.write('/* GENERATED by tools/gen_routine_decls.py - one prototype per ASM region (nesR_<address>). */\n#ifndef NES_RACE_DECL_H\n#define NES_RACE_DECL_H\n#include "nes_machine.h"\n')
    for a in addrs:
        names = ', '.join(cg.byaddr[a]['names'])
        f.write('void nesR_%04X(NesMachine *m); /* %s */\n' % (a, names))
    f.write('#endif\n')
with open('tests/oracle/fallbacks.c', 'w') as f:
    f.write('/* GENERATED by tools/gen_routine_decls.py - weak stubs that run the ORIGINAL code; real ports override them. */\n')
    f.write('#include "oracle.h"\n#include "nes_race_decl.h"\n')
    for a in addrs:
        f.write('__attribute__((weak)) void nesR_%04X(NesMachine *m) { oracleCallOriginal(m, 0x%04X); }\n' % (a, a))
print(len(addrs), 'routines')
