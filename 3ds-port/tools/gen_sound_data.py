#!/usr/bin/env python3
"""Generate source/sound_data.c (sound driver tables + music sequences).

usage: gen_sound_data.py <prg.bin> <out.c>
<prg.bin> is the 16 KiB fixed bank built from Excitebike/bank_FF.asm by
tools/asm_to_prg.py. The window is CPU $F9A2-$FFFF (see sound_driver.h).
"""
import sys

BASE, END = 0xF9A2, 0x10000

def main():
    prg = open(sys.argv[1], "rb").read()
    if len(prg) != 0x4000:
        sys.exit("expected a 16 KiB PRG bank")
    win = prg[BASE - 0xC000:END - 0xC000]
    lines = ["/* Generated by tools/gen_sound_data.py from Excitebike/bank_FF.asm. Do not edit. */",
             '#include "sound_driver.h"', "",
             "const uint8_t kSoundData[SOUND_DATA_SIZE] = {"]
    for i in range(0, len(win), 16):
        lines.append("    " + ", ".join("0x%02X" % b for b in win[i:i + 16]) + ",")
    lines += ["};", ""]
    open(sys.argv[2], "w").write("\n".join(lines))

main()
